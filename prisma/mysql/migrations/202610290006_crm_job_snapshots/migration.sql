-- All-stage CRM source inventory. Existing Job/Bill/Payment values are untouched.
CREATE TABLE `CrmImportRun` (
    `id` VARCHAR(100) NOT NULL,
    `crmOrganizationId` VARCHAR(100) NOT NULL,
    `dataCenter` VARCHAR(2) NOT NULL,
    `environment` VARCHAR(10) NOT NULL,
    `sourceModule` VARCHAR(100) NOT NULL,
    `initiatedById` VARCHAR(100) NOT NULL,
    `scopeHash` CHAR(64) NOT NULL,
    `mappingJson` JSON NOT NULL,
    `fieldsJson` JSON NOT NULL,
    `status` VARCHAR(20) NOT NULL DEFAULT 'RUNNING',
    `lastPage` INTEGER NOT NULL DEFAULT 0,
    `lastPageHash` CHAR(64) NULL,
    `nextPageToken` TEXT NULL,
    `listingComplete` BOOLEAN NOT NULL DEFAULT false,
    `snapshotCount` INTEGER NOT NULL DEFAULT 0,
    `mappedCount` INTEGER NOT NULL DEFAULT 0,
    `canonicalCount` INTEGER NOT NULL DEFAULT 0,
    `unassignedCount` INTEGER NOT NULL DEFAULT 0,
    `reviewCount` INTEGER NOT NULL DEFAULT 0,
    `lastErrorCode` VARCHAR(100) NULL,
    `startedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `completedAt` DATETIME(3) NULL,
    INDEX `CrmImportRun_source_started_idx` (`crmOrganizationId`, `dataCenter`, `environment`, `startedAt`),
    PRIMARY KEY (`id`),
    CONSTRAINT `CrmImportRun_initiatedById_fkey` FOREIGN KEY (`initiatedById`) REFERENCES `User` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT `CrmImportRun_status_check` CHECK (`status` IN ('RUNNING','PARTIAL','COMPLETE','FAILED')),
    CONSTRAINT `CrmImportRun_counts_check` CHECK (`lastPage` >= 0 AND `snapshotCount` >= 0 AND `mappedCount` >= 0 AND `canonicalCount` >= 0 AND `unassignedCount` >= 0 AND `reviewCount` >= 0),
    CONSTRAINT `CrmImportRun_complete_check` CHECK (`status` <> 'COMPLETE' OR (`listingComplete` = true AND `completedAt` IS NOT NULL AND `canonicalCount` + `unassignedCount` + `reviewCount` = `snapshotCount`))
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin;

CREATE TABLE `CrmJobSnapshot` (
    `id` VARCHAR(100) NOT NULL,
    `crmOrganizationId` VARCHAR(100) NOT NULL,
    `dataCenter` VARCHAR(2) NOT NULL,
    `environment` VARCHAR(10) NOT NULL,
    `sourceModule` VARCHAR(100) NOT NULL,
    `externalCrmId` VARCHAR(100) NOT NULL,
    `companyId` VARCHAR(100) NULL,
    `booksOrganizationId` VARCHAR(100) NULL,
    `jobNumber` TEXT NULL,
    `normalizedJobNumber` VARCHAR(255) NULL,
    `name` TEXT NULL,
    `customerId` VARCHAR(100) NULL,
    `customerName` TEXT NULL,
    `currencyCode` VARCHAR(20) NULL,
    `amount` VARCHAR(100) NULL,
    `approvedVariations` VARCHAR(100) NULL,
    `stage` TEXT NULL,
    `canonicalJobId` VARCHAR(100) NULL,
    `linkStatus` VARCHAR(40) NOT NULL DEFAULT 'PENDING',
    `sourceModifiedAt` VARCHAR(60) NULL,
    `sourceRecordJson` JSON NOT NULL,
    `importRunId` VARCHAR(100) NOT NULL,
    `importedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `lastSeenAt` DATETIME(3) NOT NULL,
    `isStale` BOOLEAN NOT NULL DEFAULT false,
    UNIQUE INDEX `CrmJobSnapshot_source_external_key` (`crmOrganizationId`, `dataCenter`, `environment`, `sourceModule`, `externalCrmId`),
    INDEX `CrmJobSnapshot_companyId_normalizedJobNumber_idx` (`companyId`, `normalizedJobNumber`),
    INDEX `CrmJobSnapshot_companyId_canonicalJobId_idx` (`companyId`, `canonicalJobId`),
    INDEX `CrmJobSnapshot_canonicalJobId_companyId_idx` (`canonicalJobId`, `companyId`),
    INDEX `CrmJobSnapshot_importRunId_linkStatus_idx` (`importRunId`, `linkStatus`),
    PRIMARY KEY (`id`),
    CONSTRAINT `CrmJobSnapshot_companyId_fkey` FOREIGN KEY (`companyId`) REFERENCES `Company` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT `CrmJobSnapshot_canonicalJobId_companyId_fkey` FOREIGN KEY (`canonicalJobId`, `companyId`) REFERENCES `Job` (`id`, `companyId`) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT `CrmJobSnapshot_importRunId_fkey` FOREIGN KEY (`importRunId`) REFERENCES `CrmImportRun` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT `CrmJobSnapshot_link_status_check` CHECK (`linkStatus` IN ('PENDING','READY','UNASSIGNED_COMPANY','INVALID_SOURCE','DUPLICATE_JOB_NUMBER','LOCAL_CONFLICT','SOURCE_CHANGED')),
    CONSTRAINT `CrmJobSnapshot_link_company_check` CHECK ((`canonicalJobId` IS NULL OR `companyId` IS NOT NULL) AND (`linkStatus` <> 'READY' OR (`canonicalJobId` IS NOT NULL AND `companyId` IS NOT NULL)))
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin;
