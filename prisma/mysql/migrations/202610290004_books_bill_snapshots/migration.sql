-- Read-only Books copies. No canonical Bill, Payment, Job or outbound queue records change.
CREATE TABLE `BooksImportRun` (
    `id` VARCHAR(100) NOT NULL,
    `companyId` VARCHAR(100) NOT NULL,
    `organizationId` VARCHAR(100) NOT NULL,
    `organizationName` VARCHAR(200) NOT NULL,
    `dataCenter` VARCHAR(2) NOT NULL,
    `environment` VARCHAR(10) NOT NULL,
    `initiatedById` VARCHAR(100) NOT NULL,
    `status` VARCHAR(20) NOT NULL DEFAULT 'RUNNING',
    `lastPage` INTEGER NOT NULL DEFAULT 0,
    `lastPageHash` CHAR(64) NULL,
    `listingComplete` BOOLEAN NOT NULL DEFAULT false,
    `listedCount` INTEGER NOT NULL DEFAULT 0,
    `detailCount` INTEGER NOT NULL DEFAULT 0,
    `lastErrorCode` VARCHAR(100) NULL,
    `startedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `completedAt` DATETIME(3) NULL,
    UNIQUE INDEX `BooksImportRun_id_companyId_key` (`id`, `companyId`),
    INDEX `BooksImportRun_companyId_startedAt_idx` (`companyId`, `startedAt`),
    INDEX `BooksImportRun_destination_status_idx` (`organizationId`, `dataCenter`, `environment`, `status`),
    PRIMARY KEY (`id`),
    CONSTRAINT `BooksImportRun_companyId_fkey` FOREIGN KEY (`companyId`) REFERENCES `Company` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT `BooksImportRun_initiatedById_fkey` FOREIGN KEY (`initiatedById`) REFERENCES `User` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT `BooksImportRun_status_check` CHECK (`status` IN ('RUNNING', 'PARTIAL', 'COMPLETE', 'FAILED')),
    CONSTRAINT `BooksImportRun_counts_check` CHECK (`lastPage` >= 0 AND `listedCount` >= 0 AND `detailCount` >= 0 AND `detailCount` <= `listedCount`),
    CONSTRAINT `BooksImportRun_complete_check` CHECK (`status` <> 'COMPLETE' OR (`listingComplete` = true AND `detailCount` = `listedCount` AND `completedAt` IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin;

CREATE TABLE `BooksBill` (
    `id` VARCHAR(100) NOT NULL,
    `companyId` VARCHAR(100) NOT NULL,
    `organizationId` VARCHAR(100) NOT NULL,
    `organizationName` VARCHAR(200) NOT NULL,
    `dataCenter` VARCHAR(2) NOT NULL,
    `environment` VARCHAR(10) NOT NULL,
    `externalBillId` VARCHAR(100) NOT NULL,
    `billNumber` VARCHAR(500) NOT NULL,
    `vendorId` VARCHAR(100) NOT NULL,
    `vendorName` VARCHAR(500) NOT NULL,
    `status` VARCHAR(100) NOT NULL,
    `currencyCode` CHAR(3) NOT NULL,
    `billDate` DATE NULL,
    `dueDate` DATE NULL,
    `subtotal` VARCHAR(100) NULL,
    `taxTotal` VARCHAR(100) NULL,
    `total` VARCHAR(100) NOT NULL,
    `balance` VARCHAR(100) NOT NULL,
    `paymentMade` VARCHAR(100) NULL,
    `vendorCreditsApplied` VARCHAR(100) NULL,
    `sourceModifiedAt` VARCHAR(60) NULL,
    `sourceSummary` JSON NOT NULL,
    `sourceDetail` JSON NULL,
    `lastImportRunId` VARCHAR(100) NOT NULL,
    `detailImportRunId` VARCHAR(100) NULL,
    `importedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `lastSeenAt` DATETIME(3) NOT NULL,
    `detailFetchedAt` DATETIME(3) NULL,
    `isStale` BOOLEAN NOT NULL DEFAULT false,
    UNIQUE INDEX `BooksBill_destination_external_key` (`organizationId`, `dataCenter`, `environment`, `externalBillId`),
    INDEX `BooksBill_companyId_status_billDate_idx` (`companyId`, `status`, `billDate`),
    INDEX `BooksBill_companyId_currencyCode_billDate_idx` (`companyId`, `currencyCode`, `billDate`),
    INDEX `BooksBill_companyId_billNumber_idx` (`companyId`, `billNumber`),
    INDEX `BooksBill_lastImportRunId_companyId_idx` (`lastImportRunId`, `companyId`),
    INDEX `BooksBill_detailImportRunId_companyId_idx` (`detailImportRunId`, `companyId`),
    PRIMARY KEY (`id`),
    CONSTRAINT `BooksBill_companyId_fkey` FOREIGN KEY (`companyId`) REFERENCES `Company` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT `BooksBill_lastImportRunId_companyId_fkey` FOREIGN KEY (`lastImportRunId`, `companyId`) REFERENCES `BooksImportRun` (`id`, `companyId`) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT `BooksBill_detailImportRunId_companyId_fkey` FOREIGN KEY (`detailImportRunId`, `companyId`) REFERENCES `BooksImportRun` (`id`, `companyId`) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin;
