CREATE TABLE `IncomingSyncState` (
  `id` VARCHAR(100) NOT NULL,
  `target` VARCHAR(10) NOT NULL,
  `organizationId` VARCHAR(100) NOT NULL,
  `dataCenter` VARCHAR(2) NOT NULL,
  `environment` VARCHAR(10) NOT NULL,
  `companyId` VARCHAR(100) NULL,
  `scopeHash` CHAR(64) NOT NULL,
  `status` VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  `checkpoint` JSON NULL,
  `watermark` DATETIME(3) NULL,
  `lastReconciledAt` DATETIME(3) NULL,
  `nextRunAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `backoffUntil` DATETIME(3) NULL,
  `lastAttemptAt` DATETIME(3) NULL,
  `lastSuccessAt` DATETIME(3) NULL,
  `lastHeartbeatAt` DATETIME(3) NULL,
  `lastErrorCode` VARCHAR(100) NULL,
  `failures` INTEGER NOT NULL DEFAULT 0,
  `processedCount` INTEGER NOT NULL DEFAULT 0,
  `providerReads` INTEGER NOT NULL DEFAULT 0,
  `leaseToken` VARCHAR(64) NULL,
  `leaseExpiresAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `IncomingSyncState_source_key` (`target`,`organizationId`,`dataCenter`,`environment`),
  INDEX `IncomingSyncState_nextRunAt_leaseExpiresAt_idx` (`nextRunAt`,`leaseExpiresAt`),
  INDEX `IncomingSyncState_companyId_idx` (`companyId`),
  CONSTRAINT `IncomingSyncState_companyId_fkey` FOREIGN KEY (`companyId`) REFERENCES `Company` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `IncomingSyncState_source_check` CHECK ((`target`='ZOHO' AND `companyId` IS NOT NULL) OR (`target`='CRM' AND `companyId` IS NULL)),
  CONSTRAINT `IncomingSyncState_status_check` CHECK (`status` IN ('PENDING','RUNNING','IDLE','RETRY','WAITING_QUOTA','BLOCKED')),
  CONSTRAINT `IncomingSyncState_lease_check` CHECK ((`leaseToken` IS NULL AND `leaseExpiresAt` IS NULL) OR (`leaseToken` IS NOT NULL AND `leaseExpiresAt` IS NOT NULL)),
  CONSTRAINT `IncomingSyncState_counts_check` CHECK (`failures`>=0 AND `processedCount`>=0 AND `providerReads`>=0)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin;
