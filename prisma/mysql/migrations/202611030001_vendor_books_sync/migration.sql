-- Additive supplier synchronization state; existing vendor/bill data is preserved.
CREATE TABLE `VendorBooksSync` (
  `id` VARCHAR(100) NOT NULL,
  `vendorId` VARCHAR(100) NOT NULL,
  `companyId` VARCHAR(100) NOT NULL,
  `organizationId` VARCHAR(100) NOT NULL,
  `dataCenter` VARCHAR(2) NOT NULL,
  `environment` VARCHAR(10) NOT NULL,
  `initiatedById` VARCHAR(100) NOT NULL,
  `status` VARCHAR(16) NOT NULL DEFAULT 'QUEUED',
  `sourceHash` CHAR(64) NOT NULL,
  `snapshot` JSON NOT NULL,
  `externalVendorId` VARCHAR(100) NULL,
  `attempts` INTEGER NOT NULL DEFAULT 0,
  `submittedAt` DATETIME(3) NULL,
  `nextAttemptAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `leaseToken` CHAR(64) NULL,
  `leaseUntil` DATETIME(3) NULL,
  `errorCode` VARCHAR(80) NULL,
  `lastError` VARCHAR(500) NULL,
  `completedAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `VendorBooksSync_vendor_destination_key` (`vendorId`,`organizationId`,`dataCenter`,`environment`),
  INDEX `VendorBooksSync_vendorId_companyId_idx` (`vendorId`,`companyId`),
  INDEX `VendorBooksSync_status_nextAttemptAt_leaseUntil_idx` (`status`,`nextAttemptAt`,`leaseUntil`),
  INDEX `VendorBooksSync_companyId_idx` (`companyId`),
  INDEX `VendorBooksSync_initiatedById_idx` (`initiatedById`),
  CONSTRAINT `VendorBooksSync_vendor_company_fkey` FOREIGN KEY (`vendorId`,`companyId`) REFERENCES `Vendor` (`id`,`companyId`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `VendorBooksSync_initiatedById_fkey` FOREIGN KEY (`initiatedById`) REFERENCES `User` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `VendorBooksSync_status_check` CHECK (`status` IN ('QUEUED','PROCESSING','UNKNOWN','BLOCKED','FAILED','SYNCED')),
  CONSTRAINT `VendorBooksSync_attempts_check` CHECK (`attempts` >= 0),
  CONSTRAINT `VendorBooksSync_snapshot_check` CHECK (JSON_TYPE(`snapshot`) = 'OBJECT')
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin;
