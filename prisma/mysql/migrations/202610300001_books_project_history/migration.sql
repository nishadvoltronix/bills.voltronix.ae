-- Provider relationships are read-only history evidence, never inferred job/bill allocation.
CREATE TABLE `BooksProjectAssociation` (
    `id` VARCHAR(100) NOT NULL,
    `companyId` VARCHAR(100) NOT NULL,
    `organizationId` VARCHAR(100) NOT NULL,
    `dataCenter` VARCHAR(2) NOT NULL,
    `environment` VARCHAR(10) NOT NULL,
    `booksProjectId` VARCHAR(100) NOT NULL,
    `projectName` VARCHAR(500) NOT NULL,
    `zprojectsProjectId` VARCHAR(100) NOT NULL,
    `portalId` VARCHAR(100) NOT NULL,
    `crmOrganizationId` VARCHAR(100) NOT NULL,
    `crmDataCenter` VARCHAR(2) NOT NULL,
    `crmEnvironment` VARCHAR(10) NOT NULL,
    `dealIds` JSON NOT NULL,
    `sourceProject` JSON NOT NULL,
    `sourceDealsPages` JSON NOT NULL,
    `sourceCrmRecords` JSON NOT NULL,
    `sourceHash` CHAR(64) NOT NULL,
    `status` VARCHAR(20) NOT NULL DEFAULT 'VERIFIED',
    `verifiedAt` DATETIME(3) NOT NULL,
    `validUntil` DATETIME(3) NOT NULL,
    `nextRefreshAt` DATETIME(3) NOT NULL,
    `lastAttemptAt` DATETIME(3) NOT NULL,
    `lastErrorCode` VARCHAR(100) NULL,
    `failures` INTEGER NOT NULL DEFAULT 0,
    `backoffUntil` DATETIME(3) NULL,
    `leaseToken` VARCHAR(64) NULL,
    `leaseExpiresAt` DATETIME(3) NULL,
    `importedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updatedAt` DATETIME(3) NOT NULL,
    PRIMARY KEY (`id`),
    UNIQUE INDEX `BooksProjectAssociation_source_project_key` (`organizationId`, `dataCenter`, `environment`, `booksProjectId`),
    INDEX `BooksProjectAssociation_company_status_idx` (`companyId`, `status`, `validUntil`),
    INDEX `BooksProjectAssociation_refresh_idx` (`nextRefreshAt`),
    INDEX `BooksProjectAssociation_crm_source_idx` (`crmOrganizationId`, `crmDataCenter`, `crmEnvironment`),
    CONSTRAINT `BooksProjectAssociation_company_fkey` FOREIGN KEY (`companyId`) REFERENCES `Company` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT `BooksProjectAssociation_status_check` CHECK (`status` IN ('VERIFIED', 'UNLINKED', 'STALE')),
    CONSTRAINT `BooksProjectAssociation_json_check` CHECK (JSON_TYPE(`dealIds`) = 'ARRAY' AND JSON_TYPE(`sourceProject`) = 'OBJECT' AND JSON_TYPE(`sourceDealsPages`) = 'ARRAY' AND JSON_TYPE(`sourceCrmRecords`) = 'ARRAY'),
    CONSTRAINT `BooksProjectAssociation_dates_check` CHECK (`validUntil` > `verifiedAt` AND `nextRefreshAt` >= `verifiedAt`),
    CONSTRAINT `BooksProjectAssociation_links_check` CHECK ((`status` <> 'VERIFIED' OR JSON_LENGTH(`dealIds`) > 0) AND (`status` <> 'UNLINKED' OR JSON_LENGTH(`dealIds`) = 0)),
    CONSTRAINT `BooksProjectAssociation_lease_check` CHECK ((`leaseToken` IS NULL AND `leaseExpiresAt` IS NULL) OR (`leaseToken` IS NOT NULL AND `leaseExpiresAt` IS NOT NULL)),
    CONSTRAINT `BooksProjectAssociation_failures_check` CHECK (`failures` >= 0)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin;
